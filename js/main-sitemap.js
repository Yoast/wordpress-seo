( () => {
	const XHTML_NAMESPACE = "http://www.w3.org/1999/xhtml";
	const SITEMAP_NAMESPACE = "http://www.sitemaps.org/schemas/sitemap/0.9";

	/**
	 * Creates a link element.
	 *
	 * @param {string}  url    The URL to link to.
	 * @param {string}  text   The link text.
	 * @param {boolean} newTab Whether the link opens in a new tab.
	 *
	 * @returns {Element} The link element.
	 */
	const createLink = ( url, text, newTab ) => {
		const link = document.createElementNS( XHTML_NAMESPACE, "a" );
		link.setAttribute( "href", url );
		if ( newTab ) {
			link.setAttribute( "target", "_blank" );
			link.setAttribute( "rel", "noopener" );
		}
		link.textContent = text;

		return link;
	};

	/**
	 * Adds the introduction with its links, which replaces the introduction that the stylesheet generates.
	 *
	 * @returns {void}
	 */
	const addIntroduction = () => {
		const root = document.documentElement;
		const introduction = document.createElementNS( XHTML_NAMESPACE, "p" );

		introduction.append(
			"Generated by ",
			createLink( "https://yoa.st/1y5", "Yoast SEO", true ),
			", this is an XML Sitemap, meant for consumption by search engines.",
			document.createElementNS( XHTML_NAMESPACE, "br" ),
			"You can find more information about XML sitemaps on ",
			createLink( "https://sitemaps.org", "sitemaps.org", true ),
			"."
		);

		root.prepend( introduction );
		root.setAttribute( "data-introduction", "" );
	};

	/**
	 * Turns the URLs of the sitemap entries into links.
	 *
	 * @returns {void}
	 */
	const linkLocations = () => {
		for ( const location of document.getElementsByTagNameNS( SITEMAP_NAMESPACE, "loc" ) ) {
			const url = location.textContent.trim();
			if ( /^https?:\/\//i.test( url ) ) {
				location.replaceChildren( createLink( url, url, false ) );
			}
		}
	};

	/**
	 * Makes the sitemap interactive.
	 *
	 * @returns {void}
	 */
	const initialize = () => {
		const rootName = document.documentElement.localName;
		if ( rootName !== "urlset" && rootName !== "sitemapindex" ) {
			return;
		}

		addIntroduction();
		linkLocations();
	};

	if ( document.readyState === "loading" ) {
		document.addEventListener( "DOMContentLoaded", initialize );
	} else {
		initialize();
	}
} )();
